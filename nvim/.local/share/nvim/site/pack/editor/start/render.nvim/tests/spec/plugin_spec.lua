describe("plugin/render.lua", function()
  it("registers the command and the key without loading the plugin", function()
    vim.cmd.runtime("plugin/render.lua")
    assert.same(2, vim.fn.exists(":Render"))
    assert.truthy(vim.fn.maparg("<leader>rv", "n") ~= "")
    assert.is_nil(package.loaded["render.view"])
  end)

  it("a key moved by setup{} is moved, not doubled", function()
    require("render").setup({ keys = { toggle = "<leader>R" } })
    assert.same("", vim.fn.maparg("<leader>rv", "n"))
    assert.truthy(vim.fn.maparg("<leader>R", "n") ~= "")
    require("render").setup({ keys = { toggle = false } })
    assert.same("", vim.fn.maparg("<leader>R", "n"))
  end)
end)
